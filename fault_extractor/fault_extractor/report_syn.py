def report_synthesis(
    similar_fault_info: Dict[str, float],
    reference_data_path: str | Path = DEFAULT_REFERENCE_DATA_PATH,
) -> str:
    """Build a Markdown report from similar historical work-order references.

    Args:
        similar_fault_info: Mapping in the form
            {work_order_no: similarity_float_between_0_and_1}. The caller is
            expected to supply already-filtered top similar documented faults.
        reference_data_path: Path to a JSON file generated by
            work_order_reference_parser. By default this points to
            ./output/reference_data_with_cause_inferenced.json.

    Returns:
        A professional Markdown report as a Python str.

    Raises:
        TypeError: If similar_fault_info is not a mapping.
        ValueError: If a supplied similarity score is not numeric or is outside
            the 0..1 range.
        FileNotFoundError: If reference_data_path does not exist.
        json.JSONDecodeError: If reference_data_path is not valid JSON.
    """
    details = report_synthesis_details(similar_fault_info, reference_data_path)
    normalized_similarity = details["normalized_similarity"]
    if not normalized_similarity:
        return _empty_report()
    if not details["cases"]:
        return _no_match_report(
            normalized_similarity,
            Path(reference_data_path),
            details["missing_work_orders"],
        )

    return _render_markdown_report(
        cases=details["cases"],
        synthesis_facts=details["synthesis_facts"],
        narrative=details["narrative"],
        missing_work_orders=details["missing_work_orders"],
        reference_data_path=Path(reference_data_path),
    )


def report_synthesis_details(
    similar_fault_info: Dict[str, float],
    reference_data_path: str | Path = DEFAULT_REFERENCE_DATA_PATH,
) -> Dict[str, Any]:
    """Return source facts and synthesis separately for structured report UIs."""
    normalized_similarity = _normalize_similar_fault_info(similar_fault_info)
    empty: Dict[str, Any] = {
        "normalized_similarity": normalized_similarity,
        "cases": [],
        "missing_work_orders": [],
        "synthesis_facts": {},
        "narrative": {},
    }
    if not normalized_similarity:
        return empty

    reference_data = _load_reference_data(reference_data_path)
    cases, missing_work_orders = _select_reference_cases(normalized_similarity, reference_data)
    if not cases:
        empty["missing_work_orders"] = missing_work_orders
        return empty

    synthesis_facts = _derive_synthesis_facts(cases)
    narrative = _llm_synthesis(cases, synthesis_facts)
    narrative_source = "llm"
    if narrative is None:
        narrative = _deterministic_synthesis(cases, synthesis_facts)
        narrative_source = "deterministic_fallback"

    return {
        "normalized_similarity": normalized_similarity,
        "cases": cases,
        "missing_work_orders": missing_work_orders,
        "synthesis_facts": synthesis_facts,
        "narrative": narrative,
        "narrative_source": narrative_source,
    }


def _normalize_similar_fault_info(similar_fault_info: Mapping[str, Any]) -> List[Tuple[str, float]]:
    if not isinstance(similar_fault_info, Mapping):
        raise TypeError("similar_fault_info must be a mapping like {work_order_no: similarity}.")

    normalized: List[Tuple[str, float]] = []
    for work_order_raw, similarity_raw in similar_fault_info.items():
        work_order = str(work_order_raw).strip()
        if not work_order:
            continue
        similarity = _coerce_similarity(similarity_raw, work_order)
        normalized.append((work_order, similarity))

    normalized.sort(key=lambda item: (-item[1], item[0]))
    return normalized


def _coerce_similarity(value: Any, work_order: str) -> float:
    if isinstance(value, str):
        text = value.strip()
        if text.endswith("%"):
            text = text[:-1].strip()
            try:
                similarity = float(text) / 100.0
            except ValueError as exc:
                raise ValueError(f"Similarity for work order {work_order!r} is not numeric: {value!r}") from exc
        else:
            try:
                similarity = float(text)
            except ValueError as exc:
                raise ValueError(f"Similarity for work order {work_order!r} is not numeric: {value!r}") from exc
    else:
        try:
            similarity = float(value)
        except (TypeError, ValueError) as exc:
            raise ValueError(f"Similarity for work order {work_order!r} is not numeric: {value!r}") from exc

    if not 0.0 <= similarity <= 1.0:
        raise ValueError(
            f"Similarity for work order {work_order!r} must be between 0 and 1, got {similarity!r}."
        )
    return similarity


def _load_reference_data(reference_data_path: str | Path) -> Dict[str, Dict[str, Any]]:
    path = Path(reference_data_path).expanduser().resolve()
    if not path.exists():
        raise FileNotFoundError(f"Reference data JSON was not found: {path}")

    with path.open("r", encoding="utf-8") as f:
        raw = json.load(f)

    indexed: Dict[str, Dict[str, Any]] = {}
    if isinstance(raw, Mapping):
        for key, value in raw.items():
            if not isinstance(value, Mapping):
                continue
            entry = dict(value)
            key_text = str(key).strip()
            work_order = str(entry.get("work_order") or key_text).strip()
            if key_text:
                indexed[key_text] = entry
            if work_order:
                indexed[work_order] = entry
    elif isinstance(raw, list):
        for value in raw:
            if not isinstance(value, Mapping):
                continue
            entry = dict(value)
            work_order = str(
                entry.get("work_order")
                or entry.get("Work Order NO.")
                or entry.get("work_order_no")
                or ""
            ).strip()
            if work_order:
                indexed[work_order] = entry
    else:
        raise ValueError("Reference data JSON must be an object keyed by work order or a list of records.")

    return indexed


def _select_reference_cases(
    normalized_similarity: Sequence[Tuple[str, float]],
    reference_data: Mapping[str, Mapping[str, Any]],
) -> Tuple[List[Dict[str, Any]], List[str]]:
    cases: List[Dict[str, Any]] = []
    missing: List[str] = []

    for rank, (work_order, similarity) in enumerate(normalized_similarity, start=1):
        entry = reference_data.get(work_order)
        if entry is None:
            missing.append(work_order)
            continue
        cases.append(_case_from_reference(rank, work_order, similarity, entry))

    return cases, missing


def _case_from_reference(
    rank: int,
    work_order: str,
    similarity: float,
    entry: Mapping[str, Any],
) -> Dict[str, Any]:
    treatment_pairs = _pair_components_events(entry.get("treatment_components"), entry.get("treatment_events"))
    phenomenon_pairs = _pair_components_events(entry.get("phenomenon_component"), entry.get("phenomenon_events"))
    cause_pairs = _pair_components_events(entry.get("cause_components"), entry.get("cause_events"))

    action_items = treatment_pairs or _split_action_text(entry.get("action"))
    component_items = _unique(
        _split_components(entry.get("component"))
        + _as_clean_list(entry.get("phenomenon_component"))
        + _as_clean_list(entry.get("cause_components"))
        + _as_clean_list(entry.get("treatment_components"))
    )

    return {
        "rank": rank,
        "work_order": work_order,
        "similarity": round(similarity, 4),
        "fault": _safe_text(entry.get("fault")),
        "evidence": _safe_text(entry.get("evidence")),
        "component": _safe_text(entry.get("component")),
        "components": component_items,
        "cause": _safe_text(entry.get("cause")),
        "cause_is_inferred": _contains_inference_marker(entry.get("cause")),
        "action": _safe_text(entry.get("action")),
        "action_items": action_items,
        "result": _safe_text(entry.get("result")),
        "phenomenon": phenomenon_pairs,
        "cause_signals": cause_pairs,
        "treatments": treatment_pairs,
        "phenomenon_components": _as_clean_list(entry.get("phenomenon_component")),
        "phenomenon_events": _as_clean_list(entry.get("phenomenon_events")),
        "cause_components": _as_clean_list(entry.get("cause_components")),
        "cause_events": _as_clean_list(entry.get("cause_events")),
        "treatment_components": _as_clean_list(entry.get("treatment_components")),
        "treatment_events": _as_clean_list(entry.get("treatment_events")),
        "equip_model": _safe_text(entry.get("equip_model")),
        "equip_instance": _safe_text(entry.get("equip_instance")),
        "equip_unit": _safe_text(entry.get("equip_unit")),
        "replace_in_part": _as_clean_list(entry.get("replace_in_part")),
        "replace_out_part": _as_clean_list(entry.get("replace_out_part")),
    }


def _derive_synthesis_facts(cases: Sequence[Mapping[str, Any]]) -> Dict[str, Any]:
    component_scores: Dict[str, float] = defaultdict(float)
    cause_component_scores: Dict[str, float] = defaultdict(float)
    action_scores: Dict[str, float] = defaultdict(float)
    phenomenon_scores: Dict[str, float] = defaultdict(float)
    cause_scores: Dict[str, float] = defaultdict(float)
    part_codes: List[str] = []

    for case in cases:
        weight = float(case.get("similarity") or 0.0)
        for component in case.get("components", []):
            component_scores[component] += weight
        for component in case.get("cause_components", []):
            cause_component_scores[component] += weight * 1.5
            component_scores[component] += weight * 0.75
        for action in case.get("action_items", []):
            action_scores[action] += weight
        for event in case.get("phenomenon_events", []):
            phenomenon_scores[event] += weight
        cause = _safe_text(case.get("cause"))
        if not _is_na(cause):
            cause_scores[cause] += weight
        for part in list(case.get("replace_in_part", [])) + list(case.get("replace_out_part", [])):
            if not _is_na(part):
                part_codes.append(part)

    top_case = dict(cases[0])
    inferred_count = sum(1 for case in cases if case.get("cause_is_inferred"))
    direct_count = len(cases) - inferred_count

    return {
        "top_case_work_order": top_case.get("work_order"),
        "top_case_fault": top_case.get("fault"),
        "top_case_similarity": top_case.get("similarity"),
        "case_count": len(cases),
        "similarity_range": [min(float(c.get("similarity") or 0.0) for c in cases), max(float(c.get("similarity") or 0.0) for c in cases)],
        "top_components": _top_weighted_items(component_scores, 8),
        "top_cause_components": _top_weighted_items(cause_component_scores, 6),
        "top_actions": _top_weighted_items(action_scores, 8),
        "top_phenomenon_events": _top_weighted_items(phenomenon_scores, 5),
        "top_causes": _top_weighted_items(cause_scores, 5),
        "unique_part_codes": _unique(part_codes)[:12],
        "inferred_cause_count": inferred_count,
        "direct_cause_count": direct_count,
    }


def _top_weighted_items(scores: Mapping[str, float], limit: int) -> List[Dict[str, Any]]:
    ranked = sorted(
        ((item, score) for item, score in scores.items() if item and not _is_na(item)),
        key=lambda pair: (-pair[1], pair[0].lower()),
    )
    return [{"item": item, "score": round(score, 3)} for item, score in ranked[:limit]]


def _llm_synthesis(
    cases: Sequence[Mapping[str, Any]],
    synthesis_facts: Mapping[str, Any],
) -> Optional[Dict[str, List[str]]]:
    if _env_flag("REPORT_SYN_DISABLE_LLM"):
        return None
    if not DEFAULT_CONFIG_PATH.exists():
        return None

    payload = {
        "similarity_score_meaning": "External time-series similarity score between the new fault and documented old faults. It is trustworthy for reference ranking, but not root-cause proof.",
        "reference_cases": list(cases[:MAX_CASES_FOR_LLM]),
        "derived_facts": dict(synthesis_facts),
        "required_style": "Markdown report will be assembled by code. Return concise JSON bullets only.",
    }

    result = call_llm(
        {
            "system_prompt": LLM_SYSTEM_PROMPT,
            "prompt": "Synthesize the following source-grounded facts into the required JSON object:\n"
            + json.dumps(payload, ensure_ascii=False, indent=2),
            "temperature": 0.1,
            "top_p": 0.2,
            "do_sample": False,
            "max_tokens": 1800,
            "response_format": {"type": "json_object"},
            "thinking": {"type": "disabled"},
            # Keep direct demos responsive; failures fall back to deterministic synthesis.
            "timeout_sec": float(os.environ.get("REPORT_SYN_LLM_TIMEOUT_SEC", "30")),
            "max_retries": int(os.environ.get("REPORT_SYN_LLM_MAX_RETRIES", "0")),
            "retry_interval_sec": float(os.environ.get("REPORT_SYN_LLM_RETRY_INTERVAL_SEC", "0.5")),
        },
        config_path=DEFAULT_CONFIG_PATH,
    )
    if not result.get("success"):
        return None

    parsed = _json_from_text(result.get("content", ""))
    if not isinstance(parsed, Mapping):
        return None

    cleaned: Dict[str, List[str]] = {}
    for key in ("situation_assessment", "recommended_steps", "document_focus", "cautions"):
        items = parsed.get(key, [])
        cleaned[key] = _clean_bullet_list(items, max_items=8)
    if not any(cleaned.values()):
        return None
    return cleaned


def _deterministic_synthesis(
    cases: Sequence[Mapping[str, Any]],
    synthesis_facts: Mapping[str, Any],
) -> Dict[str, List[str]]:
    top_case = cases[0]
    top_components = _items_only(synthesis_facts.get("top_components", []), limit=4)
    top_cause_components = _items_only(synthesis_facts.get("top_cause_components", []), limit=4)
    top_actions = _items_only(synthesis_facts.get("top_actions", []), limit=5)
    top_events = _items_only(synthesis_facts.get("top_phenomenon_events", []), limit=3)
    top_causes = _items_only(synthesis_facts.get("top_causes", []), limit=3)

    situation = [
        f"最优先参考工单为 {top_case['work_order']}，相似度 {_format_similarity(top_case['similarity'])}；其记录故障为：{top_case['fault']}。",
    ]
    if top_events:
        situation.append("相似历史案例中反复出现的现象主要为：" + "、".join(top_events) + "。")
    if top_components:
        situation.append("相似案例集中涉及的部件为：" + "、".join(top_components) + "。")
    if top_causes:
        situation.append("建议对照验证的历史原因或假设为：" + "；".join(top_causes) + "。")

    recommended = [
        "对照匹配工单核对 TMS/ER 信息、受影响单元、发生时刻、重复次数和运行位置，先确认是否属于同一故障模式。",
        "复位或进一步测试前先保存并下载诊断日志，并记录复位或动车后故障是否复现。",
        "优先执行非侵入式检查，包括相关回路检查、VCB/APC/ATR 功能测试、复位验证，以及适用时的行车或整备检查。",
    ]
    if top_cause_components:
        recommended.append("优先检查原因侧部件或信号：" + "、".join(top_cause_components) + "。")
    elif top_components:
        recommended.append("优先检查历史案例中高频涉及的部件：" + "、".join(top_components) + "。")
    if top_actions:
        recommended.append("结合旧工单复核历史处置动作：" + "；".join(top_actions) + "。")
    recommended.append("完成处置后重复相关功能测试，并持续观察无复现证据，再考虑关闭新故障。")

    document_focus = [
        "先查看相似度最高的工单，再逐项对照其证据、原因字段、动作顺序及最终结果。",
        "更换件记录仅用于追溯和兼容性核对，不应直接作为自动更换指令。",
    ]

    cautions = [
        "相似度只用于历史参考排序，不能证明新故障具有相同根因。",
        "参考数据中标记为 inferred/inferenced 的原因均应视为待验证假设。",
        "功能测试或部件更换前，应遵循已批准的安全隔离、维修手册及本地工程授权要求。",
    ]

    return {
        "situation_assessment": situation,
        "recommended_steps": recommended,
        "document_focus": document_focus,
        "cautions": cautions,
    }


def _render_markdown_report(
    cases: Sequence[Mapping[str, Any]],
    synthesis_facts: Mapping[str, Any],
    narrative: Mapping[str, Sequence[str]],
    missing_work_orders: Sequence[str],
    reference_data_path: Path,
) -> str:
    lines: List[str] = []
    lines.append("# Similar Fault Reference Report")
    lines.append("")
    lines.append("## 1. Basis and Scope")
    lines.append(
        f"- Matched historical references: **{len(cases)}** work order(s) from `{_md_escape(_display_path(reference_data_path))}`."
    )
    lines.append(
        f"- Highest-similarity reference: **{_md_escape(str(cases[0]['work_order']))}** "
        f"({_format_similarity(cases[0]['similarity'])})."
    )
    lines.append(
        "- Similarity scores are treated as reference-priority signals from time-series comparison; "
        "they do **not** prove an identical root cause."
    )
    if synthesis_facts.get("inferred_cause_count"):
        lines.append(
            f"- Cause reliability note: {synthesis_facts.get('direct_cause_count', 0)} case(s) have direct/non-marked causes and "
            f"{synthesis_facts.get('inferred_cause_count', 0)} case(s) contain inferred/inferenced cause text."
        )
    lines.append("")

    lines.append("## 2. Matched Historical Cases")
    lines.append("| Rank | Work order | Similarity | Fault | Key cause / diagnosis | Useful historical actions | Reported result |")
    lines.append("|---:|---|---:|---|---|---|---|")
    for case in cases[:MAX_CASES_IN_REPORT]:
        cause_text = _safe_text(case.get("cause"))
        if case.get("cause_is_inferred") and not _is_na(cause_text):
            cause_text = _strip_inference_marker(cause_text) + " [inferred]"
        action_text = _summarize_actions(case)
        lines.append(
            "| "
            + " | ".join(
                [
                    str(case.get("rank", "")),
                    _md_escape(str(case.get("work_order", ""))),
                    _format_similarity(float(case.get("similarity") or 0.0)),
                    _md_escape(_truncate(_safe_text(case.get("fault")), 85)),
                    _md_escape(_truncate(cause_text, 115)),
                    _md_escape(_truncate(action_text, 130)),
                    _md_escape(_truncate(_safe_text(case.get("result")), 100)),
                ]
            )
            + " |"
        )
    if len(cases) > MAX_CASES_IN_REPORT:
        lines.append(f"\nAdditional matched cases used in statistics but not shown in the table: {len(cases) - MAX_CASES_IN_REPORT}.")
    lines.append("")

    lines.append("## 3. Synthesis for the New Fault")
    lines.extend(_markdown_bullets(narrative.get("situation_assessment", [])))
    lines.append("")

    lines.append("## 4. Recommended Troubleshooting Path")
    for index, item in enumerate(_clean_bullet_list(narrative.get("recommended_steps", []), max_items=10), start=1):
        lines.append(f"{index}. {_ensure_sentence(_md_escape(item))}")
    lines.append("")

    lines.append("## 5. Components, Actions, and Documents to Prioritize")
    top_components = _items_only(synthesis_facts.get("top_components", []), limit=8)
    top_cause_components = _items_only(synthesis_facts.get("top_cause_components", []), limit=6)
    top_actions = _items_only(synthesis_facts.get("top_actions", []), limit=8)
    part_codes = list(synthesis_facts.get("unique_part_codes", []))

    if top_cause_components:
        lines.append("- Cause-side focus: " + _md_escape(", ".join(top_cause_components)) + ".")
    if top_components:
        lines.append("- Component/document focus: " + _md_escape(", ".join(top_components)) + ".")
    if top_actions:
        lines.append("- Historically used actions to review: " + _md_escape("; ".join(top_actions)) + ".")
    if part_codes:
        lines.append("- Referenced replacement part codes: " + _md_escape(", ".join(part_codes)) + ".")
    lines.extend(_markdown_bullets(narrative.get("document_focus", [])))
    lines.append("")

    lines.append("## 6. Cautions and Limits")
    lines.extend(_markdown_bullets(narrative.get("cautions", [])))
    if missing_work_orders:
        lines.append(
            "- The following supplied work order(s) were not found in the selected reference JSON and were not used: "
            + _md_escape(", ".join(missing_work_orders))
            + "."
        )
    lines.append("")

    return "\n".join(lines).rstrip() + "\n"


def _summarize_actions(case: Mapping[str, Any]) -> str:
    items = case.get("action_items", [])
    if isinstance(items, Sequence) and not isinstance(items, (str, bytes)) and items:
        return "; ".join(str(item) for item in list(items)[:5])
    return _safe_text(case.get("action"))


def _markdown_bullets(items: Iterable[Any]) -> List[str]:
    cleaned = _clean_bullet_list(items, max_items=10)
    if not cleaned:
        return ["- N/A."]
    return [f"- {_ensure_sentence(_md_escape(item))}" for item in cleaned]


def _clean_bullet_list(items: Any, max_items: int) -> List[str]:
    if isinstance(items, str):
        raw_items = [items]
    elif isinstance(items, Iterable):
        raw_items = list(items)
    else:
        raw_items = []

    cleaned: List[str] = []
    for item in raw_items:
        text = _safe_text(item)
        text = re.sub(r"^[-*\d.\s]+", "", text).strip()
        if _is_na(text) or text in cleaned:
            continue
        cleaned.append(text)
        if len(cleaned) >= max_items:
            break
    return cleaned


def _pair_components_events(components: Any, events: Any) -> List[str]:
    # Preserve duplicate events before pairing: repeated actions such as
    # [checked, checked, replaced, replaced] carry positional meaning.
    component_list = _as_clean_list_preserve_order(components)
    event_list = _as_clean_list_preserve_order(events)
    max_len = max(len(component_list), len(event_list))
    pairs: List[str] = []
    for index in range(max_len):
        component = component_list[index] if index < len(component_list) else ""
        event = event_list[index] if index < len(event_list) else ""
        if _is_na(component) and _is_na(event):
            continue
        if _is_na(component):
            pair = event
        elif _is_na(event):
            pair = component
        else:
            pair = f"{event} {component}"
        pairs.append(pair.strip())
    return _unique(pairs)


def _split_action_text(value: Any) -> List[str]:
    text = _safe_text(value)
    if _is_na(text):
        return []
    parts = re.split(r"\s*(?:;|,\s*(?=(?:checked|replaced|reset|function tested|ride checked|downloaded|swapped|isolated|repaired)\b))\s*", text, flags=re.I)
    return _unique(part.strip(" .") for part in parts if part.strip(" ."))[:8]


def _split_components(value: Any) -> List[str]:
    if isinstance(value, (list, tuple, set)):
        return _as_clean_list(value)
    text = _safe_text(value)
    if _is_na(text):
        return []
    return _unique(part.strip() for part in re.split(r"\s*,\s*", text) if part.strip())


def _as_clean_list(value: Any) -> List[str]:
    return _unique(_as_clean_list_preserve_order(value))


def _as_clean_list_preserve_order(value: Any) -> List[str]:
    if value is None:
        return []
    if isinstance(value, str):
        if _is_na(value):
            return []
        raw_items = [value]
    elif isinstance(value, Iterable):
        raw_items = list(value)
    else:
        raw_items = [value]

    cleaned: List[str] = []
    for item in raw_items:
        text = _safe_text(item)
        if not _is_na(text):
            cleaned.append(text)
    return cleaned


def _safe_text(value: Any) -> str:
    if value is None:
        return "N/A"
    if isinstance(value, str):
        text = value
    else:
        text = str(value)
    text = re.sub(r"\s+", " ", text).strip()
    return text if text else "N/A"


def _is_na(value: Any) -> bool:
    text = _safe_text(value).strip().lower()
    return text in _NA_VALUES


def _strip_inference_marker(value: Any) -> str:
    return _INFERENCE_MARKER_RE.sub("", _safe_text(value)).strip() or _safe_text(value)


def _contains_inference_marker(value: Any) -> bool:
    text = _safe_text(value).lower()
    return "inferenced" in text or "inferred" in text or "inference" in text


def _unique(items: Iterable[Any]) -> List[str]:
    seen = set()
    result: List[str] = []
    for item in items:
        text = _safe_text(item)
        if _is_na(text):
            continue
        key = text.lower()
        if key in seen:
            continue
        seen.add(key)
        result.append(text)
    return result


def _items_only(weighted_items: Any, limit: int) -> List[str]:
    result: List[str] = []
    if not isinstance(weighted_items, Iterable):
        return result
    for item in list(weighted_items)[:limit]:
        if isinstance(item, Mapping):
            text = _safe_text(item.get("item"))
        else:
            text = _safe_text(item)
        if not _is_na(text):
            result.append(text)
    return result


def _display_path(path: Path) -> str:
    try:
        return str(path.expanduser().resolve().relative_to(PROJECT_ROOT))
    except Exception:
        return str(path)


def _format_similarity(similarity: float) -> str:
    return f"{float(similarity):.2%}"


def _truncate(text: str, max_len: int) -> str:
    text = _safe_text(text)
    if len(text) <= max_len:
        return text
    return text[: max_len - 1].rstrip() + "…"


def _ensure_sentence(text: str) -> str:
    text = text.strip()
    if not text:
        return "N/A."
    return text if text[-1] in ".!?。" else text + "."


def _md_escape(text: str) -> str:
    return _safe_text(text).replace("|", "\\|")


def _json_from_text(content: Any) -> Optional[Any]:
    if isinstance(content, Mapping):
        return dict(content)
    if not isinstance(content, str):
        return None
    text = _CODE_FENCE_RE.sub("", content.strip()).strip()
    try:
        return json.loads(text)
    except Exception:
        match = _JSON_OBJECT_RE.search(text)
        if not match:
            return None
        try:
            return json.loads(match.group(0))
        except Exception:
            return None


def _env_flag(name: str) -> bool:
    return os.environ.get(name, "").strip().lower() in {"1", "true", "yes", "y", "on"}


def _empty_report() -> str:
    return (
        "# Similar Fault Reference Report\n\n"
        "No similar fault entries were supplied. Provide a mapping like "
        "`{\"work_order_no\": 0.92}` so historical documents can be selected and summarized.\n"
    )


def _no_match_report(
    normalized_similarity: Sequence[Tuple[str, float]],
    reference_data_path: Path,
    missing_work_orders: Sequence[str],
) -> str:
    requested = ", ".join(f"{wo} ({_format_similarity(score)})" for wo, score in normalized_similarity)
    missing = ", ".join(missing_work_orders) if missing_work_orders else "N/A"
    return (
        "# Similar Fault Reference Report\n\n"
        "No supplied work orders were found in the selected reference JSON.\n\n"
        f"- Reference JSON: `{_md_escape(str(reference_data_path))}`\n"
        f"- Requested work orders: {_md_escape(requested)}\n"
        f"- Missing work orders: {_md_escape(missing)}\n\n"
        "Check that `similar_fault_info` uses the same work-order numbers as the parser output.\n"
    )


def _parse_similar_fault_arg(value: str) -> Dict[str, float]:
    path = Path(value)
    if path.exists():
        with path.open("r", encoding="utf-8") as f:
            raw = json.load(f)
    else:
        raw = json.loads(value)
    if not isinstance(raw, Mapping):
        raise ValueError("The similar fault input must be a JSON object mapping work_order_no to similarity.")
    return {str(k): float(v) for k, v in raw.items()}


def main() -> None:
    parser = argparse.ArgumentParser(description="Synthesize a Markdown maintenance-reference report from similar work orders.")
    parser.add_argument(
        "--similar",
        help="JSON object string or JSON file path, e.g. '{\"5001614276\": 0.94}'.",
    )
    parser.add_argument(
        "--reference",
        default=str(DEFAULT_REFERENCE_DATA_PATH),
        help="Path to reference_data JSON generated by work_order_reference_parser.",
    )
    parser.add_argument(
        "--output",
        help="Optional Markdown output path. If omitted, the report is printed only.",
    )
    parser.add_argument("--no-llm", action="store_true", help="Disable LLM synthesis and use deterministic fallback.")
    args = parser.parse_args()

    if not args.similar:
        raise SystemExit("Please provide --similar as a JSON object string or JSON file path.")

    previous_disable = os.environ.get("REPORT_SYN_DISABLE_LLM")
    if args.no_llm:
        os.environ["REPORT_SYN_DISABLE_LLM"] = "1"
    try:
        report = report_synthesis(_parse_similar_fault_arg(args.similar), args.reference)
    finally:
        if args.no_llm:
            if previous_disable is None:
                os.environ.pop("REPORT_SYN_DISABLE_LLM", None)
            else:
                os.environ["REPORT_SYN_DISABLE_LLM"] = previous_disable

    if args.output:
        output_path = Path(args.output).expanduser().resolve()
        output_path.parent.mkdir(parents=True, exist_ok=True)
        output_path.write_text(report, encoding="utf-8")
        print(f"Markdown report saved to: {output_path}")
    else:
        print(report)


if __name__ == "__main__":
    main()
